/* -------------------------------------------------------------------------- */
/* WORKFLOWS                                                                   */
/* -------------------------------------------------------------------------- */

export function getWorkflows(): Workflow[] {
  return workflows;
}

export function getWorkflowById(id: string): Workflow | undefined {
  return workflows.find((workflow) => workflow.id === id);
}

export function createWorkflow(workflow: Workflow): Workflow {
  workflows.unshift(workflow);

  addActivity({
    type: "workflow",
    title: "New workflow created",
    description: `${workflow.name} was created.`,
  });

  return workflow;
}

export function updateWorkflow(
  id: string,
  data: Partial<Workflow>
): Workflow | undefined {
  const workflow = getWorkflowById(id);

  if (!workflow) {
    return undefined;
  }

  Object.assign(workflow, {
    ...data,
    id: workflow.id,
    updatedAt: new Date().toISOString(),
  });

  return workflow;
}

export function deleteWorkflow(id: string): boolean {
  const index = workflows.findIndex(
    (workflow) => workflow.id === id
  );

  if (index === -1) {
    return false;
  }

  workflows.splice(index, 1);

  return true;
}

export function updateWorkflowStatus(
  id: string,
  status: WorkflowStatus
): Workflow | undefined {
  return updateWorkflow(id, { status });
}
export function runWorkflow(id: string) {
  const workflow = getWorkflowById(id);

  if (!workflow) {
    return undefined;
  }

  const success = Math.random() < 0.95;

  workflow.runs += 1;

  const previousRuns = workflow.runs - 1;

  workflow.successRate =
    previousRuns === 0
      ? success
        ? 100
        : 0
      : Number(
          (
            ((workflow.successRate * previousRuns +
              (success ? 100 : 0)) /
              workflow.runs)
          ).toFixed(1)
        );

  workflow.updatedAt = new Date().toISOString();

  addActivity({
    type: "workflow",
    title: `${workflow.name} executed`,
    description: success
      ? "Workflow completed successfully."
      : "Workflow execution requires review.",
  });

  return {
    workflow,
    run: {
      id: `run-${Date.now()}`,
      workflowId: workflow.id,
      status: success ? "success" : "failed",
      createdAt: new Date().toISOString(),
    },
  };
}
