export function getWorkflows(): Workflow[] { 
  return workflows; 
} 
 
export function getWorkflowById(id: string): Workflow | undefined { 
  return workflows.find((workflow) => workflow.id === id); 
} 
 
export function createWorkflow(workflow: Workflow): Workflow { 
  workflows.unshift(workflow); 
 
  addActivity({ 
    type: "workflow", 
    title: "New workflow created", 
    description: `${workflow.name} was created.`, 
  }); 
 
  return workflow; 
} 
 
export function updateWorkflow( 
  id: string, 
  data: Partial<Workflow> 
): Workflow | undefined { 
  const workflow = getWorkflowById(id); 
 
  if (!workflow) { 
    return undefined; 
  } 
 
  const previousStatus = workflow.status; 
 
  Object.assign(workflow, { 
    ...data, 
    id: workflow.id, 
    updatedAt: new Date().toISOString(), 
  }); 
 
  if ( 
    data.status && 
    data.status !== previousStatus 
  ) { 
    addActivity({ 
      type: "workflow", 
      title: `Workflow ${data.status}`, 
      description: `${workflow.name} is now ${data.status}.`, 
    }); 
  } 
 
  return workflow; 
} 
 
export function deleteWorkflow(id: string): boolean { 
  const index = workflows.findIndex( 
    (workflow) => workflow.id === id 
  ); 
 
  if (index === -1) { 
    return false; 
  } 
 
  const workflow = workflows[index]; 
 
  workflows.splice(index, 1); 
 
  addActivity({ 
    type: "workflow", 
    title: "Workflow deleted", 
    description: `${workflow.name} was removed.`, 
  }); 
 
  return true; 
} 
 
export function updateWorkflowStatus( 
  id: string, 
  status: WorkflowStatus 
): Workflow | undefined { 
  return updateWorkflow(id, { status }); 
} 
 
export function runWorkflow(id: string) { 
  const workflow = getWorkflowById(id); 
 
  if (!workflow) { 
    return undefined; 
  } 
 
  const success = Math.random() < 0.95; 
 
  workflow.runs += 1; 
 
  const previousRuns = workflow.runs - 1; 
 
  workflow.successRate = 
    previousRuns === 0 
      ? success 
        ? 100 
        : 0 
      : Number( 
          ( 
            ((workflow.successRate * previousRuns + 
              (success ? 100 : 0)) / 
              workflow.runs) 
          ).toFixed(1) 
        ); 
 
  workflow.updatedAt = new Date().toISOString(); 
 
  /* ---------------------------------------------------------------------- */ 
  /* LEAD AUTOMATION                                                        */ 
  /* ---------------------------------------------------------------------- */ 
 
  let processedLead: Lead | undefined; 
  let createdTask: Task | undefined; 
 
  if (workflow.id === "workflow-2" && leads.length > 0) { 
    processedLead = 
      leads.find((lead) => lead.status === "new") ?? 
      leads.find((lead) => lead.status === "contacted") ?? 
      leads[0]; 
 
    if (processedLead) { 
      const previousStatus = processedLead.status; 
 
      const qualified = 
        processedLead.priority === "high" || 
        processedLead.status === "contacted"; 
 
      updateLead(processedLead.id, { 
        status: qualified 
          ? "qualified" 
          : "contacted", 
        priority: qualified 
          ? "high" 
          : processedLead.priority, 
      }); 
 
      addActivity({ 
        type: "lead", 
        title: "Lead processed by AI", 
        description: `${processedLead.name} was processed by ${workflow.name}.`, 
      }); 
 
      if ( 
        qualified && 
        previousStatus !== "qualified" 
      ) { 
        addActivity({ 
          type: "ai", 
          title: "Lead qualified by AI", 
          description: `${processedLead.name} was qualified based on lead intent.`, 
        }); 
      } 
 
      /* ------------------------------------------------------------------ */ 
      /* AUTOMATIC FOLLOW-UP TASK                                           */ 
      /* ------------------------------------------------------------------ */ 
 
      if (success && qualified) { 
        const existingFollowUp = tasks.find( 
          (task) => 
            task.leadId === processedLead?.id && 
            task.workflowId === workflow.id && 
            task.status !== "completed" && 
            task.status !== "cancelled" 
        ); 
 
        if (!existingFollowUp) { 
          const taskNow = new Date(); 
 
          const dueDate = new Date(taskNow); 
 
          dueDate.setDate( 
            dueDate.getDate() + 1 
          ); 
 
          dueDate.setHours(10, 0, 0, 0); 
 
          createdTask = { 
            id: `task-${Date.now()}-${Math.random() 
              .toString(36) 
              .slice(2, 8)}`, 
            title: `Follow up with ${processedLead.name}`, 
            description: 
              `AI-generated follow-up task for ${processedLead.name} after lead qualification.`, 
            status: "pending", 
            priority: processedLead.priority, 
            dueDate: dueDate.toISOString(), 
            leadId: processedLead.id, 
            workflowId: workflow.id, 
            createdAt: taskNow.toISOString(), 
            updatedAt: taskNow.toISOString(), 
          }; 
 
          createTask(createdTask); 
 
          addActivity({ 
            type: "task", 
            title: "Follow-up task created", 
            description: 
              `${createdTask.title} was created automatically by ${workflow.name}.`, 
          }); 
        } 
      } 
    } 
  } 
 
  addActivity({ 
    type: "workflow", 
    title: `${workflow.name} executed`, 
    description: success 
      ? processedLead 
        ? `${processedLead.name} was processed successfully.` 
        : "Workflow completed successfully." 
      : "Workflow execution requires review.", 
  }); 
 
  addActivity({ 
    type: "ai", 
    title: "AI automation executed", 
    description: 
      `${workflow.name} processed an automation run.`, 
  }); 
 
  return { 
    workflow, 
    run: { 
      id: `run-${Date.now()}`, 
      workflowId: workflow.id, 
      status: success 
        ? "success" 
        : "failed", 
      createdAt: new Date().toISOString(), 
      leadId: processedLead?.id, 
      leadName: processedLead?.name, 
      taskId: createdTask?.id, 
      taskTitle: createdTask?.title, 
    }, 
  }; 
} 
 
