/* WORKFLOW DASHBOARD STATS                                                   */ 
/* -------------------------------------------------------------------------- */ 
 
export function getWorkflowDashboardStats() { 
  const totalWorkflows = workflows.length; 
 
  const activeWorkflows = workflows.filter( 
    (workflow) => workflow.status === "active" 
  ).length; 
 
  const inactiveWorkflows = workflows.filter( 
    (workflow) => workflow.status !== "active" 
  ).length; 
 
  const totalRuns = workflows.reduce( 
    (total, workflow) => total + workflow.runs, 
    0 
  ); 
 
  const successfulRuns = workflows.reduce( 
    (total, workflow) => 
      total + 
      Math.round( 
        workflow.runs * 
          (workflow.successRate / 100) 
      ), 
    0 
  ); 
 
  const failedRuns = Math.max( 
    totalRuns - successfulRuns, 
    0 
  ); 
 
  const averageSuccessRate = 
    totalWorkflows === 0 
      ? 0 
      : Number( 
          ( 
            workflows.reduce( 
              (total, workflow) => 
                total + workflow.successRate, 
              0 
            ) / totalWorkflows 
          ).toFixed(1) 
        ); 
 
  return { 
    totalWorkflows, 
    activeWorkflows, 
    inactiveWorkflows, 
    totalRuns, 
    successfulRuns, 
    failedRuns, 
    averageSuccessRate, 
  }; 
} 
 
