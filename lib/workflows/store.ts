/* DASHBOARD / ANALYTICS                                                       */
/* -------------------------------------------------------------------------- */

export function getDashboardStats() {
  const totalRuns = workflows.reduce(
    (total, workflow) => total + workflow.runs,
    0
  );

  const activeWorkflows = workflows.filter(
    (workflow) => workflow.status === "active"
  ).length;

  const successRate =
    totalRuns === 0
      ? 0
      : workflows.reduce(
          (total, workflow) =>
            total + workflow.runs * workflow.successRate,
          0
        ) / totalRuns;

  return {
    workflows: workflows.length,
    activeWorkflows,
    leads: leads.length,
    tasks: tasks.length,
    aiRuns: totalRuns,
    successRate: Number(successRate.toFixed(1)),
  };
}

export function getAnalytics() {
  const totalRuns = workflows.reduce(
    (total, workflow) => total + workflow.runs,
    0
  );

  const successfulRuns = workflows.reduce(
    (total, workflow) =>
      total +
      Math.round(
        workflow.runs * (workflow.successRate / 100)
      ),
    0
  );

  const failedRuns = Math.max(
    totalRuns - successfulRuns,
    0
  );

  const successRate =
    totalRuns === 0
      ? 0
      : Number(
          ((successfulRuns / totalRuns) * 100).toFixed(1)
        );

  return {
    totalRuns,
    successfulRuns,
    failedRuns,
    successRate,
    leadsGenerated: leads.length,
    tasksCreated: tasks.length,
    workflows: workflows.length,
    activeWorkflows: workflows.filter(
      (workflow) => workflow.status === "active"
    ).length,
  };
}

